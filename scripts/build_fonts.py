#!/usr/bin/env python3
"""Build the self-hosted font subsets (optional fonttools/brotli tooling)."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
REVISION = "e7db6ca603fd4862010383ff17ffd6cc4ffac1c0"
FONTS = [
    ("serif", "notoserifsc/NotoSerifSC%5Bwght%5D.ttf", "Atlas Serif", "200 900", "NotoSerifSC"),
    ("sans", "notosanssc/NotoSansSC%5Bwght%5D.ttf", "Atlas Sans", "100 900", "NotoSansSC"),
    ("calligraphy", "mashanzheng/MaShanZheng-Regular.ttf", "Atlas Calligraphy", "400", "MaShanZheng"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True, help="Cache directory for upstream TTFs")
    args = parser.parse_args()
    args.source_dir.mkdir(parents=True, exist_ok=True)
    dest = ROOT / "assets/fonts"
    dest.mkdir(parents=True, exist_ok=True)
    files = [ROOT / "index.html", ROOT / "css/style.css", *sorted((ROOT / "js").glob("*.js"))]
    corpus = "\n".join(p.read_text() for p in files)
    # Include escaped JS literals and Latin text entered into custom route names.
    chars = {ord(c) for c in corpus}
    chars.update(int(c, 16) for c in re.findall(r"\\u([0-9a-fA-F]{4})", corpus))
    chars.update(range(0x20, 0x250))
    chars.update(range(0x300, 0x370))
    # Calligraphy is used only for the masthead and dynasty titles, not body text.
    titles = re.findall(r'"title"\s*:\s*"([^"\\]*(?:\\.[^"\\]*)*)"', (ROOT / "js/map_data.js").read_text())
    title_text = "江山时序江山時序" + "".join(json.loads('"' + title + '"') for title in titles)
    calligraphy_chars = {ord(c) for c in title_text} | set(range(0x20, 0x250))
    css, manifest = [], {"upstreamRevision": REVISION, "fonts": []}
    for key, remote, family, weight, license_name in FONTS:
        source = args.source_dir / f"{key}.ttf"
        base = f"https://raw.githubusercontent.com/google/fonts/{REVISION}/ofl/"
        if not source.exists():
            source.write_bytes(urlopen(base + remote).read())
        license_path = dest / f"OFL-{license_name}.txt"
        if not license_path.exists():
            license_path.write_bytes(urlopen(base + remote.split('/')[0] + '/OFL.txt').read())
        license_path.write_text("\n".join(line.rstrip() for line in license_path.read_text().splitlines()) + "\n")
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        options.layout_features = ["*"]
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=calligraphy_chars if key == "calligraphy" else chars)
        sub.subset(font)
        font.flavor = "woff2"
        temporary = dest / f"{key}.woff2"
        font.save(temporary)
        digest = hashlib.sha256(temporary.read_bytes()).hexdigest()
        filename = f"{key}-{digest[:12]}.woff2"
        temporary.replace(dest / filename)
        # Only prune previous versions of this generated font, not other assets.
        for old in dest.glob(f"{key}-*.woff2"):
            if old.name != filename:
                old.unlink()
        manifest["fonts"].append({
            "family": family, "file": filename, "sha256": digest,
            "source": base + remote,
            "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "characters": "".join(chr(c) for c in sorted(font.getBestCmap())),
        })
        css.append(f"@font-face {{\n  font-family: '{family}';\n  src: url('./{filename}') format('woff2');\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n}}\n")
        print(f"{family}: {(dest / filename).stat().st_size:,} bytes, {len(font.getBestCmap())} characters")
    (dest / "fonts.css").write_text("/* Generated by scripts/build_fonts.py. */\n" + "\n".join(css))
    (dest / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
